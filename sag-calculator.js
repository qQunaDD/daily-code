const bike = prompt("Тип велосипеда (хадтейл, подвес):");
const sag = Number(prompt("Процент проседания вилки:"));

if (bike === "хардтейл") {
	if (sag >= 15 && sag <= 20) {
		alert("Вилка настроена идеально!");
	} else {
		alert("Подкачай воздух");
	}
} else if (bike === "подвес") {
	if (sag >= 25 && sag <= 30) {
		alert("Подвеска в норме!");
	} else {
		alert("Нужно настроить подвеску");
	}
} else {
	alert("Неизвестный тип байка!");
}