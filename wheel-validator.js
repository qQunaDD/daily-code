const d = Number(prompt("Введите диаметр колёс:"));
const w = Number(prompt("Введите ширину втулки в мм:"));
const n = Number(prompt("Введите кол-во спиц:"));

if ((d === 27.5 || d === 29) 
    && (w === 148) 
    && (n >= 32 || n <= 36 && n % 2 === 0)) {
	alert("Колесо подходит");
} else {
	alert("Колесо не подходит");
}